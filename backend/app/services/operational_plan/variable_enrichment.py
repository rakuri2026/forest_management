def _extract_unit(label_en: str) -> str:
    """Extract unit from English label, e.g. 'Growing Stock per ha (m³)' -> 'm³/ha'."""
    if not label_en:
        return ""
    # Common unit patterns in labels
    unit_map = {
        "sqm": "m²",
        "hectares": "ha",
        "hectare": "ha",
        "(ha)": "ha",
        "(sqm)": "m²",
        "(m)": "m",
        "(mm)": "mm",
        "(c)": "°C",
        "(m³)": "m³",
        "(m3)": "m³",
        "(cft)": "cft",
        "(t)": "tonnes",
        "(tC)": "tC",
        "(tCO₂)": "tCO₂",
        "(tco2)": "tCO₂",
        "(Mg)": "Mg",
        "(Rs)": "NPR",
        "(%)": "%",
        "percent": "%",
        "m²/ha": "m²/ha",
        "m³/ha/yr": "m³/ha/yr",
        "m³/yr": "m³/yr",
        "m³/ha": "m³/ha",
        "t/ha": "t/ha",
        "tC/ha": "tC/ha",
        "tCO₂/ha": "tCO₂/ha",
        "Mg/ha": "Mg/ha",
        "g/cm³": "g/cm³",
    }
    label_lower = label_en.lower()
    for pattern, unit in unit_map.items():
        if pattern in label_lower:
            return unit
    return ""


def enrich_variable(var: VariableDef) -> Dict:
    """Merge enrichment data into a flat dict for CSV export."""
    key = var.key
    source = var.source or ""
    category = var.category

    origin_tab, origin_tab_group = resolve_origin_tab(key, source, category)

    data_shape = DATA_SHAPES.get(key, _shape_for_type(var.var_type))
    description = DESCRIPTIONS.get(key, "")
    description_ne = DESCRIPTION_NE.get(key, "")
    example = EXAMPLE_VALUES.get(key, "")
    sub_group = SUB_GROUPS.get(key, "")
    source_desc = SOURCE_DESCRIPTIONS.get(source, "")
    used = "Yes" if key in TEMPLATE_USED else "No"
    compute_deps = "; ".join(COMPUTE_DEPENDENCIES.get(key, []))
    related = RELATED_VARIABLES.get(key, "")
    unit = _extract_unit(var.label_en)
    mock_rows = TABLE_PREVIEWS.get(key, [])
    table_columns = list(mock_rows[0].keys()) if mock_rows else []

    return {
        "key": key,
        "category": category,
        "category_name": CATEGORY_NAMES.get(category, ""),
        "origin_tab": origin_tab or "",
        "origin_tab_group": origin_tab_group,
        "sub_group": sub_group,
        "label_en": var.label_en,
        "label_ne": var.label_ne,
        "data_type": var.var_type,
        "data_shape": data_shape,
        "source_module": source,
        "source_description": source_desc,
        "auto_populate": "Yes" if var.auto_populate else "No",
        "precision": var.precision,
        "resolver": var.resolver,
        "compute_fn": var.compute_fn or "",
        "compute_dependencies": compute_deps,
        "used_in_template": used,
        "template_sections": "TBD",
        "description": description,
        "description_ne": description_ne,
        "example_value": example,
        "unit": unit,
        "collector_key_path": "",
        "related_variables": related,
        "is_chart": "Yes" if key.startswith("chart:") else "No",
        "is_map": "Yes" if key.startswith("map:") else "No",
        "is_table": "Yes" if key.startswith("table:") else "No",
        "table_columns": json.dumps(table_columns),
        "mock_rows": json.dumps(mock_rows),
    }


def get_enriched_variables() -> List[Dict]:
    """Return all 487 variables as enriched flat dicts."""
    return [enrich_variable(v) for v in get_all_variables()]


def build_csv_string(variables: List[Dict]) -> str:
    """Build a CSV string from enriched variable dicts."""
    output = io.StringIO()
    writer = csv.DictWriter(output, fieldnames=CSV_COLUMNS, extrasaction="ignore")
    writer.writeheader()
    for row in variables:
        writer.writerow(row)
    return output.getvalue()
