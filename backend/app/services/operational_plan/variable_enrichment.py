# Key prefix overrides — same source_module but different origin tab
KEY_PREFIX_TAB: Dict[str, Tuple[str, str]] = {
    "ti_": ("Total Inventory", "Data & Maps"),
}


def resolve_origin_tab(key: str, source: str, category: str) -> Tuple[Optional[str], str]:
    """Resolve (origin_tab, origin_tab_group) for a variable.

    Resolution order:
    1. Key prefix overrides (e.g., ti_* -> Total Inventory)
    2. Category-based fallback (C/E/F -> Operational Plan, D -> (computed))
    3. Source_module lookup
    """
    for prefix, tab in KEY_PREFIX_TAB.items():
        if key.startswith(prefix):
            return tab
    if category in ("C", "E", "F"):
        return ("Operational Plan", "Data & Maps")
    if category == "D":
        return (None, "(derived)")
    fallback: Tuple[Optional[str], str] = ("Operational Plan", "Data & Maps")
    return SOURCE_TAB_MAP.get(source, fallback)


